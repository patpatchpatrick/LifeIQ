        .init(
            inputSignalId: inputSignalId,
            inputTitle: inputTitle,
            outputSignalId: outputSignalId,
            outputTitle: outputTitle,
            category: category,
            recommendationFamily: .reduce,
            variants: [
                .init(
                    id: "\(idBase).carryover-clean",
                    priority: 0,
                    timing: .nextDay(
                        controlMetricId: inputSignalId,
